// Display risk in target language
export function displayRisk(risk, localeOrConfig) {
  const loc = getLocale(localeOrConfig);
  const DICT_RISK = {
    'zh-CN': {
      critical: '致命',
      high: '高危',
      medium: '中危',
      low: '低危',
      suggestion: '建议'
    },
    'en-US': {
      critical: 'Critical',
      high: 'High',
      medium: 'Medium',
      low: 'Low',
      suggestion: 'Suggestion'
    }
  };
  const dict = DICT_RISK[loc] || DICT_RISK['en-US'];
  return dict[risk] || risk;
}

