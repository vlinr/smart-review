export function t(configOrLocale, key, params) {
  const loc = getLocale(configOrLocale);
  const dict = MESSAGES[loc] || MESSAGES['en-US'];
  // AI prompts are English-only (en-US). zh-CN keeps CLI/user-facing strings; missing keys fall back.
  const msg = (Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : undefined)
    ?? MESSAGES['en-US'][key]
    ?? key;
  return format(msg, params);
}

